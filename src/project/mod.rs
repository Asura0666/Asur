//! Versioned project manifests used by `asur init` and `asur dev`.

mod compose;

pub use compose::import_compose;

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use crate::docker::{Mount, PortBinding, PullPolicy, RestartPolicy};
use crate::env::parser::{EnvFile, EnvLine};

pub const MANIFEST_FILE: &str = ".asur.toml";
pub const MANIFEST_VERSION: u32 = 1;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProjectManifest {
    pub version: u32,
    pub project: ProjectMetadata,
    #[serde(default)]
    pub services: BTreeMap<String, ServiceConfig>,
    #[serde(default)]
    pub profiles: BTreeMap<String, ProfileConfig>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProjectMetadata {
    pub name: String,
    #[serde(default = "default_env_files")]
    pub env_files: Vec<PathBuf>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ServiceConfig {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub preset: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container_name: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub ports: Vec<PortBinding>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub mounts: Vec<Mount>,
    /// Container variable -> source key in the process or project env files.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub environment: BTreeMap<String, String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub depends_on: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub health: Option<HealthCheck>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub command: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub network: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub restart: Option<RestartPolicy>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pull: Option<PullPolicy>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "lowercase", deny_unknown_fields)]
pub enum HealthCheck {
    Tcp {
        port: u16,
        #[serde(default = "default_health_timeout")]
        timeout_seconds: u64,
    },
    Command {
        command: Vec<String>,
        #[serde(default = "default_health_interval")]
        interval_seconds: u64,
        #[serde(default = "default_command_timeout")]
        timeout_seconds: u64,
        #[serde(default = "default_health_retries")]
        retries: u64,
        #[serde(default)]
        start_period_seconds: u64,
    },
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProfileConfig {
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub description: String,
    #[serde(default)]
    pub services: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct ResolvedEnvironment {
    values: HashMap<String, String>,
}

fn default_env_files() -> Vec<PathBuf> {
    vec![PathBuf::from(".env")]
}

const fn default_health_timeout() -> u64 {
    30
}

const fn default_health_interval() -> u64 {
    5
}

const fn default_command_timeout() -> u64 {
    3
}

const fn default_health_retries() -> u64 {
    5
}

impl ProjectManifest {
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            version: MANIFEST_VERSION,
            project: ProjectMetadata {
                name: sanitize_name(&name.into()),
                env_files: default_env_files(),
            },
            services: BTreeMap::new(),
            profiles: BTreeMap::new(),
        }
    }

    pub fn load(path: &Path) -> Result<Self> {
        let content = std::fs::read_to_string(path)
            .with_context(|| format!("could not read project manifest `{}`", path.display()))?;
        let manifest: Self = toml::from_str(&content)
            .with_context(|| format!("project manifest `{}` is invalid", path.display()))?;
        manifest.validate()?;
        Ok(manifest)
    }

    pub fn to_toml(&self) -> Result<String> {
        let mut output = String::from(
            "# Generated by Asur. Environment entries reference keys; secret values do not belong here.\n",
        );
        output.push_str(
            &toml::to_string_pretty(self).context("could not serialize project manifest")?,
        );
        Ok(output)
    }

    pub fn validate(&self) -> Result<()> {
        if self.version != MANIFEST_VERSION {
            bail!(
                "unsupported .asur.toml version {}; this Asur release supports version {}",
                self.version,
                MANIFEST_VERSION
            );
        }
        validate_identifier(&self.project.name, "project name")?;
        if self.services.is_empty() {
            bail!("project manifest does not define any services");
        }

        for (name, service) in &self.services {
            validate_identifier(name, "service name")?;
            match (&service.preset, &service.image) {
                (Some(_), None) | (None, Some(_)) => {}
                (Some(_), Some(_)) => {
                    bail!("service `{name}` must use either `preset` or `image`, not both")
                }
                (None, None) => bail!("service `{name}` must define `preset` or `image`"),
            }
            if let Some(container_name) = &service.container_name {
                validate_container_name(container_name)?;
            }
            for dependency in &service.depends_on {
                if dependency == name {
                    bail!("service `{name}` cannot depend on itself");
                }
                if !self.services.contains_key(dependency) {
                    bail!("service `{name}` depends on unknown service `{dependency}`");
                }
            }
            for (container_key, source_key) in &service.environment {
                validate_env_key(container_key)?;
                validate_env_key(source_key)?;
            }
            if let Some(HealthCheck::Tcp { port, .. }) = &service.health
                && !service
                    .ports
                    .iter()
                    .any(|binding| binding.container_port == *port)
            {
                bail!(
                    "service `{name}` health check uses container port {port}, but that port is not published"
                );
            }
            if let Some(HealthCheck::Command { command, .. }) = &service.health
                && command.is_empty()
            {
                bail!("service `{name}` command health check cannot be empty");
            }
        }

        for (profile, config) in &self.profiles {
            validate_identifier(profile, "profile name")?;
            for service in &config.services {
                if !self.services.contains_key(service) {
                    bail!("profile `{profile}` contains unknown service `{service}`");
                }
            }
        }
        for env_file in &self.project.env_files {
            if env_file.is_absolute()
                || env_file
                    .components()
                    .any(|component| matches!(component, std::path::Component::ParentDir))
            {
                bail!(
                    "project env file `{}` must stay inside the project directory",
                    env_file.display()
                );
            }
        }
        self.startup_waves(None)?;
        Ok(())
    }

    /// Return dependency-safe concurrency waves. Services inside one wave are
    /// independent and may be started concurrently.
    pub fn startup_waves(&self, profile: Option<&str>) -> Result<Vec<Vec<String>>> {
        let mut selected: BTreeSet<String> = if let Some(profile) = profile {
            self.profiles
                .get(profile)
                .ok_or_else(|| anyhow::anyhow!("unknown profile `{profile}`"))?
                .services
                .iter()
                .cloned()
                .collect()
        } else {
            self.services.keys().cloned().collect()
        };
        if selected.is_empty() {
            bail!("the selected profile contains no services");
        }

        let mut pending: Vec<String> = selected.iter().cloned().collect();
        while let Some(name) = pending.pop() {
            for dependency in &self.services[&name].depends_on {
                if selected.insert(dependency.clone()) {
                    pending.push(dependency.clone());
                }
            }
        }

        let mut completed = HashSet::new();
        let mut waves = Vec::new();
        while completed.len() < selected.len() {
            let wave: Vec<String> = selected
                .iter()
                .filter(|name| !completed.contains(*name))
                .filter(|name| {
                    self.services[*name]
                        .depends_on
                        .iter()
                        .all(|dependency| completed.contains(dependency))
                })
                .cloned()
                .collect();
            if wave.is_empty() {
                let unresolved: Vec<_> = selected
                    .iter()
                    .filter(|name| !completed.contains(*name))
                    .cloned()
                    .collect();
                bail!(
                    "service dependency cycle detected involving: {}",
                    unresolved.join(", ")
                );
            }
            completed.extend(wave.iter().cloned());
            waves.push(wave);
        }
        Ok(waves)
    }

    pub fn container_name(&self, service_name: &str) -> String {
        self.services[service_name]
            .container_name
            .clone()
            .unwrap_or_else(|| format!("asur-{}-{service_name}", self.project.name))
    }
}

impl ResolvedEnvironment {
    pub fn load(project_root: &Path, env_files: &[PathBuf]) -> Result<Self> {
        let mut values = HashMap::new();
        for file in env_files {
            let path = project_root.join(file);
            let content = match std::fs::read_to_string(&path) {
                Ok(content) => content,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
                Err(error) => {
                    return Err(error)
                        .with_context(|| format!("could not read `{}`", path.display()));
                }
            };
            for line in EnvFile::parse(&content).lines {
                if let EnvLine::Entry { key, value, .. } = line {
                    values.insert(key, value);
                }
            }
        }
        for (key, value) in std::env::vars() {
            values.insert(key, value);
        }
        Ok(Self { values })
    }

    pub fn resolve_service(
        &self,
        service_name: &str,
        references: &BTreeMap<String, String>,
    ) -> Result<Vec<String>> {
        references
            .iter()
            .map(|(container_key, source_key)| {
                self.values
                    .get(source_key)
                    .map(|value| format!("{container_key}={value}"))
                    .ok_or_else(|| {
                        anyhow::anyhow!(
                            "service `{service_name}` requires environment key `{source_key}`; set it in the process or a project env file"
                        )
                    })
            })
            .collect()
    }
}

pub fn find_manifest(start: &Path) -> Result<(PathBuf, ProjectManifest)> {
    for directory in start.ancestors() {
        let path = directory.join(MANIFEST_FILE);
        if path.is_file() {
            return Ok((path.clone(), ProjectManifest::load(&path)?));
        }
    }
    bail!(
        "no `{MANIFEST_FILE}` found from `{}` upward. Run `asur init` in the project directory first",
        start.display()
    )
}

pub fn sanitize_name(value: &str) -> String {
    let value = value.trim().to_ascii_lowercase();
    let mut result = String::new();
    let mut last_dash = false;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            result.push(character);
            last_dash = false;
        } else if !last_dash && !result.is_empty() {
            result.push('-');
            last_dash = true;
        }
    }
    result.trim_matches('-').to_string()
}

fn validate_identifier(value: &str, kind: &str) -> Result<()> {
    if value.is_empty()
        || value.len() > 128
        || !value
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || matches!(character, '-' | '_'))
    {
        bail!("invalid {kind} `{value}`; use letters, digits, `-`, or `_`");
    }
    Ok(())
}

fn validate_container_name(value: &str) -> Result<()> {
    if value.is_empty()
        || value.len() > 128
        || !value.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.')
        })
    {
        bail!("invalid container name `{value}`; use letters, digits, `.`, `-`, or `_`");
    }
    Ok(())
}

fn validate_env_key(value: &str) -> Result<()> {
    let mut characters = value.chars();
    let valid_start = characters
        .next()
        .is_some_and(|character| character.is_ascii_alphabetic() || character == '_');
    if !valid_start
        || !characters.all(|character| character.is_ascii_alphanumeric() || character == '_')
    {
        bail!("invalid environment key `{value}`");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_manifest() -> ProjectManifest {
        let mut manifest = ProjectManifest::new("Demo App");
        manifest.services.insert(
            "db".into(),
            ServiceConfig {
                preset: Some("postgres".into()),
                ports: vec!["5432:5432".parse().unwrap()],
                ..Default::default()
            },
        );
        manifest.services.insert(
            "api".into(),
            ServiceConfig {
                image: Some("ghcr.io/acme/api@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa".into()),
                depends_on: vec!["db".into()],
                ..Default::default()
            },
        );
        manifest
    }

    #[test]
    fn manifest_round_trip_preserves_explicit_types() {
        let manifest = sample_manifest();
        manifest.validate().unwrap();
        let encoded = manifest.to_toml().unwrap();
        let decoded: ProjectManifest = toml::from_str(&encoded).unwrap();
        assert_eq!(decoded, manifest);
    }

    #[test]
    fn dependencies_form_concurrent_waves() {
        let manifest = sample_manifest();
        assert_eq!(
            manifest.startup_waves(None).unwrap(),
            vec![vec!["db".to_string()], vec!["api".to_string()]]
        );
    }

    #[test]
    fn cycles_are_rejected() {
        let mut manifest = sample_manifest();
        manifest.services.get_mut("db").unwrap().depends_on = vec!["api".into()];
        assert!(
            manifest
                .validate()
                .unwrap_err()
                .to_string()
                .contains("cycle")
        );
    }

    #[test]
    fn profile_includes_dependencies() {
        let mut manifest = sample_manifest();
        manifest.profiles.insert(
            "minimal".into(),
            ProfileConfig {
                description: String::new(),
                services: vec!["api".into()],
            },
        );
        assert_eq!(
            manifest.startup_waves(Some("minimal")).unwrap(),
            vec![vec!["db".to_string()], vec!["api".to_string()]]
        );
    }
}
